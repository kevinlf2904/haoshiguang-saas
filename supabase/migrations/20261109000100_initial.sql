create extension if not exists pgcrypto;

create type public.member_role as enum ('owner','manager','staff');
create type public.order_status as enum ('pending','accepted','preparing','ready','completed','cancelled');
create type public.fulfillment_type as enum ('takeaway','dine_in');
create type public.payment_method as enum ('cash','online');
create type public.payment_status as enum ('unpaid','pending','paid','refunded');

create table public.tenants (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{1,48}[a-z0-9]$'),
  phone text,
  address text,
  currency text not null default 'TWD' check (currency = 'TWD'),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.memberships (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role public.member_role not null default 'staff',
  created_at timestamptz not null default now(),
  unique (tenant_id,user_id)
);

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  name text not null,
  sort_order int not null default 0,
  is_active boolean not null default true,
  unique (tenant_id,name),
  unique (id,tenant_id)
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  category_id uuid not null,
  name text not null,
  description text not null default '',
  price integer not null check (price >= 0),
  is_available boolean not null default true,
  sort_order int not null default 0,
  created_at timestamptz not null default now(),
  foreign key (category_id,tenant_id) references public.categories(id,tenant_id) on delete cascade
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete restrict,
  order_number bigint generated by default as identity,
  customer_name text not null,
  customer_phone text not null,
  fulfillment public.fulfillment_type not null,
  table_label text,
  note text not null default '',
  status public.order_status not null default 'pending',
  payment_method public.payment_method not null default 'cash',
  payment_status public.payment_status not null default 'unpaid',
  subtotal integer not null check (subtotal >= 0),
  total integer not null check (total >= 0),
  created_at timestamptz not null default now(),
  unique (tenant_id,order_number)
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  unit_price integer not null check (unit_price >= 0),
  quantity integer not null check (quantity between 1 and 99),
  line_total integer not null check (line_total >= 0)
);

create index memberships_user_idx on public.memberships(user_id);
create index products_tenant_category_idx on public.products(tenant_id,category_id,is_available);
create index orders_tenant_created_idx on public.orders(tenant_id,created_at desc);
create index order_items_order_idx on public.order_items(order_id);

create function public.is_tenant_member(target_tenant uuid)
returns boolean language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.memberships m where m.tenant_id=target_tenant and m.user_id=(select auth.uid())) $$;

create function public.has_tenant_role(target_tenant uuid, allowed public.member_role[])
returns boolean language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.memberships m where m.tenant_id=target_tenant and m.user_id=(select auth.uid()) and m.role=any(allowed)) $$;

alter table public.tenants enable row level security;
alter table public.memberships enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

create policy tenant_public_read on public.tenants for select using (is_active);
create policy tenant_member_read on public.tenants for select using (public.is_tenant_member(id));
create policy membership_read_self on public.memberships for select using (user_id=(select auth.uid()) or public.has_tenant_role(tenant_id,array['owner','manager']::public.member_role[]));
create policy categories_public_read on public.categories for select using (is_active and exists(select 1 from public.tenants t where t.id=tenant_id and t.is_active));
create policy categories_staff_manage on public.categories for all using (public.has_tenant_role(tenant_id,array['owner','manager']::public.member_role[])) with check (public.has_tenant_role(tenant_id,array['owner','manager']::public.member_role[]));
create policy products_public_read on public.products for select using (is_available and exists(select 1 from public.tenants t where t.id=tenant_id and t.is_active));
create policy products_staff_manage on public.products for all using (public.has_tenant_role(tenant_id,array['owner','manager']::public.member_role[])) with check (public.has_tenant_role(tenant_id,array['owner','manager']::public.member_role[]));
create policy orders_staff_read on public.orders for select using (public.is_tenant_member(tenant_id));
create policy orders_staff_update on public.orders for update using (public.has_tenant_role(tenant_id,array['owner','manager','staff']::public.member_role[])) with check (public.has_tenant_role(tenant_id,array['owner','manager','staff']::public.member_role[]));
create policy order_items_staff_read on public.order_items for select using (public.is_tenant_member(tenant_id));

